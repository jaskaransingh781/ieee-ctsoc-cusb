function parseArguments(argv, environment = process.env) {
  const options = {
    expectedDatabase: environment.CODEX_CLEANUP_EXPECTED_DATABASE || '',
    delete: false,
    confirmation: '',
    backupConfirmed: false,
    allowRemote: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--help' || argument === '-h') {
      options.help = true;
    } else if (argument === '--delete') {
      options.delete = true;
    } else if (argument === '--backup-confirmed') {
      options.backupConfirmed = true;
    } else if (argument === '--allow-remote') {
      options.allowRemote = true;
    } else if (argument === '--expected-database' || argument === '--confirm-delete') {
      const value = argv[index + 1];
      if (!value || value.startsWith('--')) {
        throw new Error(`${argument} requires a value.`);
      }
      index += 1;
      if (argument === '--expected-database') options.expectedDatabase = value;
      else options.confirmation = value;
    } else {
      throw new Error(`Unknown option: ${argument}`);
    }
  }

  if (!options.help && !options.expectedDatabase) {
    throw new Error('Specify --expected-database to verify the intended MongoDB database.');
  }
  if (options.delete && options.confirmation !== 'CODEX') {
    throw new Error('Deletion requires --delete --confirm-delete CODEX.');
  }
  if (options.delete && !options.backupConfirmed) {
    throw new Error('Deletion requires --backup-confirmed after a current database backup.');
  }

  return options;
}

function parseMongoUri(uri) {
  const match = uri.match(/^mongodb(?:\+srv)?:\/\/([^/?#]*)(\/[^?#]*)?/i);
  if (!match || !match[1]) throw new Error('MONGODB_URI is not a valid MongoDB connection URI.');

  const authority = match[1];
  const path = match[2] || '';
  const rawDatabase = path.slice(1);
  let databaseFromUri = '';
  try {
    databaseFromUri = rawDatabase ? decodeURIComponent(rawDatabase) : '';
  } catch {
    throw new Error('MONGODB_URI contains an invalid database path.');
  }

  const hosts = authority.slice(authority.lastIndexOf('@') + 1).split(',');
  const isRemote = !hosts.length || hosts.some((entry) => {
    if (!entry) return true;
    const host = entry.startsWith('[')
      ? entry.slice(1, entry.indexOf(']')).toLowerCase()
      : entry.split(':')[0].toLowerCase();
    return !['localhost', '127.0.0.1', '::1'].includes(host);
  });

  return { databaseFromUri, isRemote };
}

function formatCount(value) {
  return new Intl.NumberFormat('en-US').format(value);
}

function printPlan() {
  console.log('CODEX MongoDB cleanup plan (dry run unless --delete is explicitly supplied)');
  console.log('Targets are the six collections generated by the historical CODEX Mongoose models.');
  for (const entry of codexCollections) {
    console.log(`  ${entry.collection} (${entry.model}): ${entry.criteria}`);
  }
  console.log('CYBERHUNT protection: cyberhuntstates is not a deletion target; only _id "cyberhunt" is counted.');
}

async function readPlan(database) {
  const results = [];
  for (const entry of codexCollections) {
    const model = mongoose.models[entry.model]
      || mongoose.model(entry.model, new mongoose.Schema({}, { strict: false }));
    if (model.collection.name !== entry.collection) {
      throw new Error(`Historical collection mapping for ${entry.model} does not match Mongoose's collection name. No deletion was attempted.`);
    }
    const collection = database.collection(model.collection.name);
    const [total, matching] = await Promise.all([
      collection.countDocuments({}),
      collection.countDocuments(entry.filter),
    ]);
    results.push({ ...entry, total, matching, manualReview: total - matching, collection });
  }
  const cyberhuntStateCount = await database.collection('cyberhuntstates').countDocuments({ _id: 'cyberhunt' });
  return { results, cyberhuntStateCount };
}

function printCounts(results, cyberhuntStateCount) {
  console.log('\nMatching CODEX documents before deletion:');
  for (const result of results) {
    console.log(`  ${result.collection.collectionName}: ${formatCount(result.matching)} match(es)`);
    if (result.manualReview) {
      console.log(`    ${formatCount(result.manualReview)} non-matching document(s) left untouched; manual review required`);
    }
  }
  console.log(`  Total matching: ${formatCount(results.reduce((total, result) => total + result.matching, 0))}`);
  console.log(`  CYBERHUNT singleton documents observed (not a deletion target): ${formatCount(cyberhuntStateCount)}`);
}

async function deleteMatches(results) {
  let failed = false;
  console.log('\nDeleting only the listed filter matches:');
  for (const result of results) {
    try {
      const outcome = await result.collection.deleteMany(result.filter);
      console.log(`  ${result.collection.collectionName}: deleted ${formatCount(outcome.deletedCount)} of ${formatCount(result.matching)} planned document(s)`);
      if (outcome.deletedCount !== result.matching) failed = true;
    } catch (error) {
      failed = true;
      const code = error?.codeName || error?.code || error?.name || 'unknown error';
      console.error(`  ${result.collection.collectionName}: deletion failed (${code}); other collections may already have been processed`);
    }
  }
  return failed;
}

export async function runCleanup(argv = process.argv.slice(2), environment = process.env) {
  const options = parseArguments(argv, environment);
  if (options.help) {
    console.log([
      'Usage: node scripts/cleanup-codex-mongodb.js --expected-database <name> [options]',
      '',
      'Default: connect read-only for an exact count report; no deletion.',
      '  --expected-database <name>  Required target database name.',
      '  --allow-remote              Permit a remote MongoDB URI (otherwise refused).',
      '  --delete                    Enable scoped deleteMany operations.',
      '  --confirm-delete CODEX      Required explicit deletion confirmation.',
      '  --backup-confirmed          Confirm a current backup exists before deletion.',
      '',
      'MONGODB_URI is loaded from the environment or the project .env file.',
      'Do not run deletion against production without verifying the target and backup.',
    ].join('\n'));
    return 0;
  }

  const uri = environment.MONGODB_URI;
  if (!uri) throw new Error('MONGODB_URI is not configured; no database connection was attempted.');

  const target = parseMongoUri(uri);
  if (!target.databaseFromUri) {
    throw new Error('MONGODB_URI does not specify a database name. No connection was attempted; configure a URI with an explicit database path.');
  }
  if (target.databaseFromUri && target.databaseFromUri !== options.expectedDatabase) {
    throw new Error(`Configured URI targets database "${target.databaseFromUri}", not the expected database "${options.expectedDatabase}". No connection was attempted.`);
  }
  if (target.isRemote && !options.allowRemote) {
    throw new Error('The configured MongoDB URI appears remote. Re-run with --allow-remote only after verifying this is the intended database.');
  }

  printPlan();
  console.log(`\nExpected database: ${options.expectedDatabase}`);
  console.log(`Operation: ${options.delete ? 'DELETE (explicitly authorized)' : 'read-only dry run'}`);
  if (options.delete) {
    console.log('Backup acknowledgement: received. Stop any legacy CODEX server before continuing.');
  }

  let deletionStarted = false;
  try {
    await mongoose.connect(uri, {
      dbName: options.expectedDatabase,
      serverSelectionTimeoutMS: 10_000,
    });
    const database = mongoose.connection.db;
    if (database.databaseName !== options.expectedDatabase) {
      throw new Error(`Connected database "${database.databaseName}" does not match the expected database. No deletion was attempted.`);
    }

    const before = await readPlan(database);
    printCounts(before.results, before.cyberhuntStateCount);
    if (!options.delete) {
      console.log('\nDry run complete. No documents were changed.');
      return 0;
    }

    deletionStarted = true;
    const hadFailures = await deleteMatches(before.results);
    const after = await readPlan(database);
    console.log('\nPost-operation verification:');
    for (const result of after.results) {
      console.log(`  ${result.collection.collectionName}: ${formatCount(result.matching)} matching CODEX document(s) remain`);
    }
    const cyberhuntUnchanged = before.cyberhuntStateCount === after.cyberhuntStateCount;
    console.log(`  CYBERHUNT singleton count unchanged: ${cyberhuntUnchanged ? 'yes' : 'no (database activity may be concurrent)'}`);
    const codexRemains = after.results.some((result) => result.matching > 0);
    if (hadFailures || codexRemains || !cyberhuntUnchanged) {
      console.error('Cleanup incomplete or concurrent changes detected. Review the per-collection counts and errors; do not blindly rerun.');
      return 1;
    }
    console.log('All documents matching the CODEX criteria are absent.');
    return 0;
  } catch (error) {
    if (!deletionStarted) throw error;
    const code = error?.codeName || error?.code || error?.name || 'unknown error';
    throw new Error(`Cleanup may be partial: deletion started but verification did not finish (${code}). Inspect the reported per-collection results and manually verify before rerunning.`);
  } finally {
    await mongoose.disconnect();
  }
}

const invokedPath = process.argv[1] ? pathToFileURL(process.argv[1]).href : '';
if (import.meta.url === invokedPath) {
  runCleanup().then((status) => {
    process.exitCode = status;
  }).catch((error) => {
    console.error(`Cleanup stopped safely: ${error.message}`);
    process.exitCode = 1;
  });
}

export { codexCollections, parseArguments, parseMongoUri };
